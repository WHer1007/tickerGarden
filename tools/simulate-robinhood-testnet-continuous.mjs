import {readProjectEnv} from "./environment.mjs";
import {reviewPath, simulationPath} from "./robinhood-deployment-run.mjs";
import fs from 'node:fs';
import path from 'node:path';
import {spawnSync} from 'node:child_process';
import {fileURLToPath} from 'node:url';
import {assertArtifactSourcesCurrent} from './verify-v1-build-inputs.mjs';

const root = fileURLToPath(new URL('../', import.meta.url));
if (process.argv.length !== 2) throw Error('No arguments supported');
const input = path.join(root, `${reviewPath}`);
const output = path.join(root, `${simulationPath}`);
fs.mkdirSync(output, {recursive: true});
const cfg = Object.fromEntries(fs.readFileSync(input + '/candidate.public.env', 'utf8').split('\n').filter((line) => line).map((line) => { const i = line.indexOf('='); return [line.slice(0, i), line.slice(i + 1)]; }));
if (cfg.V1_EXPECTED_CHAIN_ID !== '46630') throw Error('Wrong chain config');
const local = readProjectEnv();
if (!local.ALCHEMY_API_KEY) throw Error('Missing ALCHEMY_API_KEY');
const rpc = `https://robinhood-testnet.g.alchemy.com/v2/${local.ALCHEMY_API_KEY}`;
const script = 'DeployV1RobinhoodTestnetContinuousHolders';
const artifact = JSON.parse(fs.readFileSync(root + `contracts/out-v1/${script}.s.sol/${script}.json`));
assertArtifactSourcesCurrent(artifact, root + 'contracts', script);
const env = {...process.env, ...cfg}; delete env.DEPLOYER_PRIVATE_KEY;
const result = spawnSync(process.execPath, ['tools/run-forge.mjs', 'script', `script/v1/${script}.s.sol:${script}`, '--sig', 'simulate()', '--rpc-url', rpc, '--sender', cfg.V1_EXPECTED_DEPLOYER, '--non-interactive', '-vv'], {cwd: root, env, encoding: 'utf8', maxBuffer: 40 * 1024 * 1024});
const log = ((result.stdout ?? '') + (result.stderr ?? '')).split(rpc).join('[ROBINHOOD_TESTNET_RPC]');
fs.writeFileSync(output + '/simulation.log', log);
if (result.status !== 0 || !log.includes('Script ran successfully.')) throw Error('Simulation failed; see sanitized simulation.log');
const source = root + `contracts/broadcast/${script}.s.sol/46630/dry-run/simulate-latest.json`;
fs.copyFileSync(source, output + '/unsigned-transactions.json');
console.log(JSON.stringify({status: 'UNSIGNED_SIMULATION_COMPLETED_NOT_BROADCAST', output}));
