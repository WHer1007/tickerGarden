import fs from 'node:fs';
import {createPublicClient,createWalletClient,http,encodeDeployData,keccak256,getContractAddress} from '../apps/web/node_modules/viem/_esm/index.js';
import {privateKeyToAccount} from '../apps/web/node_modules/viem/_esm/accounts/index.js';
import {arbitrumSepolia} from '../apps/web/node_modules/viem/_esm/chains/index.js';
const walletPath='/Users/dear/.config/tickergarden/testnet-wallets/arbitrum-sepolia.json';
const st=fs.lstatSync(walletPath);if(st.isSymbolicLink()||(st.mode&0o077)!==0)throw Error('Unsafe wallet permissions');
const wallet=JSON.parse(fs.readFileSync(walletPath));
const account=privateKeyToAccount(wallet.privateKey);
if(wallet.chainId!==421614||account.address.toLowerCase()!==wallet.address.toLowerCase())throw Error('Wallet mismatch');
const rpc='https://sepolia-rollup.arbitrum.io/rpc';
const client=createPublicClient({chain:arbitrumSepolia,transport:http(rpc)});
if(await client.getChainId()!==421614)throw Error('Wrong network');
const artifact=JSON.parse(fs.readFileSync('contracts/out-v1/ArbitrumTestTreasury.sol/ArbitrumTestTreasury.json'));
const recordPath='deployments/manifests/arbitrum-sepolia-421614.test-treasury-r2.json';
let record=fs.existsSync(recordPath)?JSON.parse(fs.readFileSync(recordPath)):undefined;
if(!record){
 const nonce=await client.getTransactionCount({address:account.address,blockTag:'pending'});
 const data=encodeDeployData({abi:artifact.abi,bytecode:artifact.bytecode.object,args:[account.address]});
 const gas=await client.estimateGas({account:account.address,data});
 const price=await client.getGasPrice();
 if(gas*price*2n>await client.getBalance({address:account.address}))throw Error('Insufficient balance');
 console.log(JSON.stringify({stage:'estimated',gas:gas.toString(),estimatedWei:(gas*price).toString(),nonce}));
 if(process.argv[2]!=='broadcast')process.exit(0);
 const signer=createWalletClient({account,chain:arbitrumSepolia,transport:http(rpc)});
 const hash=await signer.deployContract({abi:artifact.abi,bytecode:artifact.bytecode.object,args:[account.address],nonce,gas:gas*12n/10n});
 record={chainId:421614,owner:account.address,address:getContractAddress({from:account.address,nonce:BigInt(nonce)}),transactionHash:hash,status:'SUBMITTED'};
 fs.writeFileSync(recordPath,JSON.stringify(record,null,2)+'\n');
}
const receipt=await client.waitForTransactionReceipt({hash:record.transactionHash,confirmations:2});
if(receipt.status!=='success')throw Error('Receiver deployment reverted');
const code=await client.getCode({address:record.address});
const owner=await client.readContract({address:record.address,abi:artifact.abi,functionName:'owner'});
const normalized=Buffer.from(code.slice(2),'hex');
for(const ranges of Object.values(artifact.deployedBytecode.immutableReferences??{}))for(const r of ranges)normalized.fill(0,r.start,r.start+r.length);
if(normalized.toString('hex')!==artifact.deployedBytecode.object.slice(2))throw Error('Treasury runtime does not match current artifact');
if(owner.toLowerCase()!==account.address.toLowerCase()||!code||code==='0x')throw Error('Receiver verification failed');
record={...record,status:'DEPLOYED_VERIFIED',runtimeCodeHash:keccak256(code),blockNumber:receipt.blockNumber.toString(),gasUsed:receipt.gasUsed.toString()};
fs.writeFileSync(recordPath,JSON.stringify(record,null,2)+'\n');
fs.writeFileSync('deployments/manifests/arbitrum-sepolia-421614.test-treasury.json',JSON.stringify(record,null,2)+'\n');
const p='deployments/config/arbitrum-sepolia.public.env';let env=fs.readFileSync(p,'utf8');
env=env.replace(/^V1_PLATFORM_TREASURY=.*$/m,'V1_PLATFORM_TREASURY='+record.address).replace(/^V1_PLATFORM_TREASURY_CODEHASH=.*$/m,'V1_PLATFORM_TREASURY_CODEHASH='+record.runtimeCodeHash);
fs.writeFileSync(p,env);console.log(JSON.stringify(record,null,2));
