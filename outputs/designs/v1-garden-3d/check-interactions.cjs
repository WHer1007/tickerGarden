const {chromium}=require(process.env.PLAYWRIGHT_MODULE || 'playwright');
const assert=require('node:assert/strict');
const path=require('node:path').resolve('outputs/designs/v1-garden-3d')+'/';
require('node:fs').mkdirSync(path,{recursive:true});
(async()=>{
 const browser=await chromium.launch({executablePath:process.env.CHROME_PATH || '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--use-angle=swiftshader','--enable-unsafe-swiftshader']});
 const page=await browser.newPage({viewport:{width:1440,height:1050},deviceScaleFactor:1});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));
 try {
 await page.goto('http://127.0.0.1:5193/',{waitUntil:'networkidle'});
 await page.locator('.garden-ready').waitFor();
 assert.equal(await page.locator('.garden-fruit-label').count(),10);
 await page.getByRole('button',{name:'Pause motion',exact:true}).click();
 await page.getByRole('button',{name:'Explore NVDA, NVIDIA',exact:true}).click();
 assert.match(await page.locator('[data-garden-status]').textContent(),/NVDA · NVIDIA/);
 assert.equal(await page.getByRole('button',{name:'Explore NVDA, NVIDIA',exact:true}).getAttribute('aria-pressed'),'true');
 await page.getByRole('button',{name:'Explore next ticker',exact:true}).click();
 assert.equal(await page.locator('[data-garden-symbol]').textContent(),'AAPL');
 const before=await page.getByRole('button',{name:'Explore NVDA, NVIDIA',exact:true}).boundingBox();
 const box=await page.locator('[data-garden-viewport]').boundingBox();
 await page.mouse.move(box.x+box.width*.48,box.y+box.height*.78);
 await page.mouse.down();await page.mouse.move(box.x+box.width*.73,box.y+box.height*.78,{steps:15});await page.mouse.up();
 await page.waitForFunction(x=>Math.abs(document.querySelector('.garden-fruit-label').getBoundingClientRect().x-x)>8,before.x);
 await page.screenshot({path:path+'desktop-rotated.png'});
 await page.getByRole('button',{name:'Reset view',exact:true}).click();
 assert.equal(await page.locator('[data-garden-status]').textContent(),'Garden view reset.');
 await page.waitForFunction(x=>Math.abs(document.querySelector('.garden-fruit-label').getBoundingClientRect().x-x)<4,before.x);
 await page.screenshot({path:path+'desktop.png'});
 await page.locator('[data-garden-viewport]').focus();
 await page.keyboard.press('ArrowRight');
 await page.waitForFunction(x=>Math.abs(document.querySelector('.garden-fruit-label').getBoundingClientRect().x-x)>3,before.x);
 await page.keyboard.press('Home');
 await page.emulateMedia({reducedMotion:'reduce'});
 assert.equal(await page.getByRole('button',{name:'Resume motion',exact:true}).getAttribute('aria-pressed'),'false');
 await page.setViewportSize({width:390,height:844});
 await page.locator('[data-garden]').scrollIntoViewIfNeeded();
 await page.getByRole('button',{name:'Explore TSLA, Tesla',exact:true}).click();
 assert.match(await page.locator('[data-garden-status]').textContent(),/TSLA · Tesla/);
 await page.screenshot({path:path+'mobile.png'});
 assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),true);
 await page.evaluate(()=>document.querySelector('.garden-viewport canvas').getContext('webgl2').getExtension('WEBGL_lose_context').loseContext());
 await page.locator('.garden-ready').waitFor({state:'detached'});
 await page.locator('.tree-base').waitFor({state:'visible'});
 assert.equal(await page.locator('.garden-viewport').isVisible(),false);
 await page.screenshot({path:path+'fallback.png'});
 assert.deepEqual(errors,[]);
 console.log('PASS: WebGL mount, 10 fruits without Read API, selection, next ticker, drag rotation, reset, keyboard rotation, reduced motion, mobile selection/no overflow, context-loss fallback; no page errors.');
 } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exit(1)});
