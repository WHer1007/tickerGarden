import { mkdir, readFile, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const indexerRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const repositoryRoot = path.resolve(indexerRoot, "..");
const manifestPath = path.join(repositoryRoot, "spec/v1_product_artifact_manifest.json");
const outputPath = path.join(indexerRoot, "src/generated/v1-events.ts");

const solidityTypeToTs = (type) => {
  if (type.endsWith("[]")) return `readonly ${solidityTypeToTs(type.slice(0, -2))}[]`;
  if (type === "bool") return "boolean";
  if (/^u?int\d*$/.test(type)) return "bigint";
  if (type === "address" || type === "string" || type.startsWith("bytes")) return "string";
  return "unknown";
};

const manifest = JSON.parse(await readFile(manifestPath, "utf8"));
const sources = manifest.modules.map((entry) => ({
  module: entry.module,
  artifact: path.join(repositoryRoot, entry.interfaceArtifact),
}));
sources.push({
  module: "UniswapV4PoolManager",
  artifact: path.join(repositoryRoot, "contracts/out-v1/IPoolManager.sol/IPoolManager.json"),
  only: new Set(["Donate", "Swap"]),
});

const bySignature = new Map();
for (const source of sources) {
  const artifact = JSON.parse(await readFile(source.artifact, "utf8"));
  for (const item of artifact.abi) {
    if (item.type !== "event" || source.only && !source.only.has(item.name)) continue;
    const signature = `${item.name}(${item.inputs.map((input) => input.type).join(",")})`;
    const current = bySignature.get(signature);
    if (current) {
      current.modules.push(source.module);
      continue;
    }
    bySignature.set(signature, {
      signature,
      name: item.name,
      modules: [source.module],
      inputs: item.inputs.map(({ name, type, indexed }) => ({ name, type, indexed })),
    });
  }
}

const events = [...bySignature.values()].sort((a, b) => a.signature.localeCompare(b.signature));
const lines = [
  "// Generated by scripts/generate-v1-events.mjs from compiled V1 interface artifacts.",
  "// Do not edit by hand.",
  "",
  "export type Hex = `0x${string}`;",
  "",
  "export interface V1EventArgsBySignature {",
];
for (const event of events) {
  lines.push(`  readonly \"${event.signature}\": {`);
  for (const input of event.inputs) lines.push(`    readonly ${input.name}: ${solidityTypeToTs(input.type)};`);
  lines.push("  };");
}
lines.push("}", "", "export type V1EventSignature = keyof V1EventArgsBySignature;", "");
lines.push("export interface V1EventAbiInput {", "  readonly name: string;", "  readonly type: string;", "  readonly indexed: boolean;", "}", "");
lines.push("export interface V1EventAbiEntry {", "  readonly signature: V1EventSignature;", "  readonly name: string;", "  readonly modules: readonly string[];", "  readonly inputs: readonly V1EventAbiInput[];", "}", "");
lines.push("export const V1_EVENT_ABI = [");
for (const event of events) {
  lines.push("  {");
  lines.push(`    signature: \"${event.signature}\",`);
  lines.push(`    name: \"${event.name}\",`);
  lines.push(`    modules: ${JSON.stringify(event.modules)},`);
  lines.push(`    inputs: ${JSON.stringify(event.inputs)},`);
  lines.push("  },");
}
lines.push("] as const satisfies readonly V1EventAbiEntry[];", "");

const generated = `${lines.join("\n")}\n`;
if (process.argv.includes("--check")) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    process.stderr.write("Generated V1 event catalog is stale; run npm run generate:events.\n");
    process.exitCode = 1;
  }
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generated);
}
